@Composable
internal fun JuusChatTopBar(
    title: String,
    subtitle: String?,
    onBack: () -> Unit,
    onHistoryClick: () -> Unit,
    onBackgroundClick: () -> Unit,
    onSettingsClick: () -> Unit,
    isDark: Boolean
) {
    // JUUSTAGRAM 设计：毛玻璃头部 bg-white/85 + backdrop-blur(8px)
    val bgColor = if (isDark) JuusColors.Dark.FooterBg else JuusColors.FooterBg
    val contentColor = if (isDark) JuusColors.Dark.TextPrimary else JuusColors.TextPrimary
    val subColor = if (isDark) JuusColors.Dark.TextSecondary else JuusColors.TextSecondary
    val borderColor = if (isDark) JuusColors.Dark.FooterBorder else JuusColors.FooterBorder
    val accentColor = if (isDark) JuusColors.Dark.AiName else JuusColors.Primary

    Row(
        modifier = Modifier
            .fillMaxWidth()
            .background(bgColor)
            .drawBehind {
                val strokeWidth = 1.dp.toPx()
                drawLine(
                    color = borderColor,
                    start = Offset(0f, size.height),
                    end = Offset(size.width, size.height),
                    strokeWidth = strokeWidth
                )
            }
            .padding(horizontal = AppSpacing.Xs, vertical = AppSpacing.Xs),
        verticalAlignment = Alignment.CenterVertically
    ) {
        IconButton(onClick = onBack) {
            Icon(
                Icons.AutoMirrored.Rounded.ArrowBack,
                contentDescription = "返回",
                tint = contentColor
            )
        }
        Column(
            modifier = Modifier
                .weight(1f)
                .padding(start = AppSpacing.Xs)
        ) {
            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                Text(
                    text = title,
                    style = AppTypography.TitleMediumBold,
                    color = contentColor,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
            }
            if (subtitle != null) {
                Text(
                    text = subtitle,
                    style = AppTypography.LabelSmall,
                    color = subColor,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis
                )
            }
        }
        Row(verticalAlignment = Alignment.CenterVertically) {
            IconButton(onClick = onBackgroundClick) {
                Icon(
                    Icons.Rounded.Image,
                    contentDescription = "聊天背景",
                    tint = subColor,
                    modifier = Modifier.size(20.dp)
                )
            }
            IconButton(onClick = onHistoryClick) {
                Icon(
                    Icons.Rounded.ChatBubbleOutline,
                    contentDescription = "历史对话",
                    tint = subColor,
                    modifier = Modifier.size(20.dp)
                )
            }
            IconButton(onClick = onSettingsClick) {
                Icon(
                    Icons.Rounded.Settings,
                    contentDescription = "啾信设置",
                    tint = subColor,
                    modifier = Modifier.size(20.dp)
                )
            }
        }
    }
}
